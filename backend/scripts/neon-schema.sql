-- Neon/PostgreSQL schema for the Travel App Spring Boot models.
-- This script is idempotent: it creates missing tables/indexes but does not drop data.

CREATE TABLE IF NOT EXISTS ms_user (
    user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_name varchar(255),
    user_full_name varchar(255),
    email varchar(255),
    phone varchar(255),
    website varchar(255),
    password_hash varchar(100),
    created_by varchar(255),
    created_date timestamp,
    updated_by varchar(255),
    updated_date timestamp,
    record_status char(1) DEFAULT 'A'
);

CREATE TABLE IF NOT EXISTS ms_customer (
    customer_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_code varchar(255),
    customer_name varchar(255),
    address varchar(255),
    tel_no varchar(255),
    created_by varchar(255),
    created_date timestamp,
    updated_by varchar(255),
    updated_date timestamp,
    record_status char(1) DEFAULT 'A'
);

CREATE TABLE IF NOT EXISTS ms_trip (
    id varchar(255) PRIMARY KEY,
    name varchar(255),
    destination varchar(255),
    date_range varchar(255),
    notes varchar(2000),
    created_by varchar(255),
    created_date timestamp,
    updated_by varchar(255),
    updated_date timestamp,
    record_status char(1) DEFAULT 'A'
);

CREATE TABLE IF NOT EXISTS ms_trip_plan (
    id varchar(255) PRIMARY KEY,
    plan_day varchar(255),
    plan_time varchar(255),
    detail varchar(2000),
    place varchar(255),
    latitude varchar(255),
    longitude varchar(255),
    trip_id varchar(255),
    created_date timestamp,
    updated_date timestamp,
    record_status char(1) DEFAULT 'A',
    CONSTRAINT fk_ms_trip_plan_trip
        FOREIGN KEY (trip_id)
        REFERENCES ms_trip (id)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS ms_trip_user (
    trip_id varchar(255) NOT NULL,
    sort_order integer NOT NULL,
    user_name varchar(255),
    CONSTRAINT pk_ms_trip_user PRIMARY KEY (trip_id, sort_order),
    CONSTRAINT fk_ms_trip_user_trip
        FOREIGN KEY (trip_id)
        REFERENCES ms_trip (id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_ms_user_record_status
    ON ms_user (record_status);

CREATE INDEX IF NOT EXISTS idx_ms_user_user_name_record_status
    ON ms_user (user_name, record_status);

CREATE INDEX IF NOT EXISTS idx_ms_customer_record_status
    ON ms_customer (record_status);

CREATE INDEX IF NOT EXISTS idx_ms_customer_name_record_status
    ON ms_customer (customer_name, record_status);

CREATE INDEX IF NOT EXISTS idx_ms_trip_record_status
    ON ms_trip (record_status);

CREATE INDEX IF NOT EXISTS idx_ms_trip_plan_trip_id
    ON ms_trip_plan (trip_id);

CREATE INDEX IF NOT EXISTS idx_ms_trip_user_trip_id
    ON ms_trip_user (trip_id);

ALTER TABLE ms_user ALTER COLUMN record_status SET DEFAULT 'A';
ALTER TABLE ms_customer ALTER COLUMN record_status SET DEFAULT 'A';
ALTER TABLE ms_trip ALTER COLUMN record_status SET DEFAULT 'A';
ALTER TABLE ms_trip_plan ALTER COLUMN record_status SET DEFAULT 'A';
